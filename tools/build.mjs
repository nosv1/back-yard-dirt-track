// Builds the page from src/page.html with src/core.js and src/ui.js inlined as one module script (the Claude
// artifact only runs inline scripts). Writes:
//   index.html           a full HTML document for GitHub Pages (doctype, viewport meta for phones)
//   build/artifact.html  the same page as a fragment, for publishing as a Claude artifact (it adds its own frame)
//   build/bundle.mjs     the joined script, so the check can syntax-check it (node --check)
// Text joining only; nothing here runs the app's code.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const MARK = '<!-- @app -->';
const BODY = '<!-- @body -->';
const IMPORT = /^import \{[^}]*\} from '\.\/core\.js';\n/m;

/** @param {string} path */
function read(path) {
  return readFileSync(new URL('../' + path, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
}

/** @param {boolean} ok @param {string} why */
function need(ok, why) {
  if (!ok) { throw new Error('build: ' + why); }
}

const page = read('src/page.html');
need(page.split(MARK).length === 2, 'src/page.html needs exactly one ' + MARK);
need(page.split(BODY).length === 2, 'src/page.html needs exactly one ' + BODY + ' between head and body');

const core = read('src/core.js').replace(/^export /gm, '');
need(!/\bexport\b/.test(core.replace(/\/\/.*$/gm, '')), 'core.js has an export the build does not handle');
need(!/^import /m.test(core), 'core.js must not import anything');

const ui = read('src/ui.js');
need(IMPORT.test(ui), "ui.js must import from './core.js' in one statement");
const uiBody = ui.replace(IMPORT, '');
need(!/^import /m.test(uiBody), 'ui.js has a second import the build does not handle');

const bundle = '// core.js\n' + core + '\n// ui.js\n' + uiBody;
need(!bundle.includes('</script'), 'the code must not contain a closing script tag');

const [head = '', body = ''] = page.replace(MARK, '<script type="module">\n' + bundle + '</script>').split(BODY);
const banner = '<!-- Built by tools/build.mjs from src/. Edit src/ and run npm run build; do not edit this file. -->\n';
const full = '<!doctype html>\n' + banner + '<html lang="en">\n<head>\n<meta charset="utf-8">\n' +
  '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n' +
  head.trim() + '\n</head>\n<body>\n' + body.trim() + '\n</body>\n</html>\n';

mkdirSync(new URL('../build/', import.meta.url), { recursive: true });
writeFileSync(new URL('../build/bundle.mjs', import.meta.url), bundle);
writeFileSync(new URL('../build/artifact.html', import.meta.url), head + body);
writeFileSync(new URL('../index.html', import.meta.url), full);
console.log('index.html and build/artifact.html built: ' + String(bundle.length) + ' bytes of script');
